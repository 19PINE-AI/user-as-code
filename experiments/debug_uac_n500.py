#!/usr/bin/env python3
"""Trace what UaC v5 does on an N=500 failure case.

Re-runs the case while capturing:
- the structured code generated by Phase 2
- the chars truncated (records vs structured-code coverage)
- the actual REPL transcript (each python() call + stdout)
- the final answer
"""
from __future__ import annotations
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from analytical_bench.runners import _uac_structure
from analytical_bench.tools import PythonREPL, run_tool_loop


def trace(case_id: str) -> None:
    cases = json.load(open(pathlib.Path(__file__).resolve().parent / "results" / "analytical_cases.json"))["cases"]
    case = next(c for c in cases if c["case_id"] == case_id)

    print(f"=== {case_id} ===")
    print(f"Q: {case['question']}")
    print(f"gold: {case['gold']}  (kind={case['answer_kind']})")
    print(f"records: {len(case['records'])}")
    raw_json = json.dumps(case["records"], indent=1)
    print(f"raw JSON chars: {len(raw_json)}")
    print()

    # Generate structured code (this is what UaC v5 does)
    code = _uac_structure(case)
    print(f"structured code chars: {len(code)}")
    print()

    repl = PythonREPL(initial_namespace={"records_raw": case["records"]}, timeout=20.0)
    pre = repl.run(code)
    print(f"--- structured code exec ---")
    print(f"  error: {pre['error']}")
    print(f"  stdout: {pre['stdout']!r}")
    if pre["error"]:
        print()
        print("STRUCTURED CODE (truncated to 2000 chars):")
        print(code[:2000])
    print()

    # Sample the namespace to see how many records made it
    n_records_probe = repl.run("""
import sys
# Find any list-like attributes that look like the records collection
for name, val in list(globals().items()):
    if name.startswith('_') or callable(val):
        continue
    if isinstance(val, list):
        print(f'  {name}: list of {len(val)} items')
        if val and hasattr(val[0], '__dataclass_fields__'):
            print(f'    fields: {list(val[0].__dataclass_fields__.keys())}')
""")
    print("--- namespace probe ---")
    print(n_records_probe["stdout"])
    print()

    sys_inst = (
        "You have a Python REPL via the `python` tool. "
        "Typed Python has been loaded: a `data` list of dataclass instances "
        "represents the user's records. The raw records are also available "
        "as `records_raw` (list of dicts). Use Python to compute the answer. "
        "Reply with ONLY the final answer on the last line."
    )
    result = run_tool_loop(
        question=case["question"],
        system_instruction=sys_inst,
        repl=repl,
        max_turns=8,
        thinking_budget=2048,
    )
    print("--- LLM trajectory ---")
    print(f"answer: {result['answer']!r}")
    print(f"turns: {result['turns']}, tool_calls: {result['tool_calls']}")
    for i, entry in enumerate(result.get("log", [])):
        print(f"\nTurn {i+1} ({entry['tool']}):")
        if entry["tool"] == "python":
            print(f"  code:\n    " + entry["code"].replace("\n", "\n    ")[:1500])
            print(f"  stdout: {entry['stdout']!r}")
            if entry["error"]:
                print(f"  error: {entry['error'][:300]}")


if __name__ == "__main__":
    cases_to_trace = sys.argv[1:] or [
        "trips_trips_long_count_n500",      # gold 180, pred 104 (count too low)
        "transactions_tx_q4_total_n500",    # gold 76429, pred 20697 (way off)
        "meetings_meet_trend_h1_h2_n500",   # gold increase, pred Decrease
    ]
    for cid in cases_to_trace:
        try:
            trace(cid)
        except Exception as e:
            import traceback
            traceback.print_exc()
        print("\n" + "=" * 80 + "\n")
